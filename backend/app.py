@contextlib.asynccontextmanager
async def lifespan(_app):
    # Daily signal refresh while the server runs (SIGNALS_REFRESH_HOURS, 0 turns it off).
    task=asyncio.create_task(run_forever()) if interval_hours() else None
    yield
    if task:
        task.cancel()
        with contextlib.suppress(asyncio.CancelledError):await task

app=FastAPI(title='FuturePath Prism — Learning Demo',version='0.1.0',lifespan=lifespan)

@app.middleware('http')
async def protect_synthetic_demo(request:Request,call_next):
    blocked=gate_response(request)
    if blocked is not None:return blocked
    return await call_next(request)
# Keeping the existing first-run database initialization and all API paths.
init()
for route in (meta, skills, careers, learning, profiles, snapshots, curator, radar,
              matches, scenarios, history, cv_upload, ai, signals, pages):
    app.include_router(route.router)
app.mount('/static',StaticFiles(directory=ROOT/'frontend'),name='static')
app.mount('/assets',StaticFiles(directory=ROOT/'frontend'/'assets'),name='original-assets')
app.mount('/uploads',StaticFiles(directory=ROOT/'frontend'/'uploads'),name='original-uploads')
